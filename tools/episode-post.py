#!/usr/bin/env python3
"""Turn YouTube episodes (episode 2 onwards) into blog posts for rasivani.com.

    python3 tools/episode-post.py YOUTUBE-FOLDER [epNN ...]

YOUTUBE-FOLDER holds studio/epNN/lines.json (every spoken line in ta/te/en) and
<tamil|telugu|english>/epNN/ with UPLOAD-epNN-<lang>.md (YouTube title and description) and the thumbnail.
content/videos/episodes.json says, per episode: the post's web address (slug, the same one the video
description links to), the day it goes live, the series name, the video's on-screen title, and the
chapters (line number where each chapter starts, with its heading in each language).

Writes content/videos/epNN.mjs and images/videos/epNN-<lang>.jpg for every episode listed.
The video links itself to the post each night (by the post link in its description or by its title).
"""
import json, os, re, shutil, sys

LANGS = {'ta': 'tamil', 'te': 'telugu', 'en': 'english'}
# Greeting and goodbye lines are part of the video, not the article
SKIP = {'வணக்கம்! RasiVani-க்கு உங்களை வரவேற்கிறோம்.', 'நன்றி! மீண்டும் சந்திப்போம்.',
        'నమస్కారం! RasiVani కి మీకు స్వాగతం.', 'ధన్యవాదాలు! మళ్ళీ కలుద్దాం.',
        'Namaste, and welcome to RasiVani.', 'Thank you, and see you again.'}


def clean_title(t):
    t = re.sub(r'\s*\|\s*RasiVani\s*$', '', t.strip())
    t = re.sub(r'#\w+', '', t)
    # an emoji between two phrases works like a colon: keep the break readable once it is gone
    emoji = lambda ch: 0x1F000 <= ord(ch) <= 0x1FAFF or 0x2300 <= ord(ch) <= 0x23FF or 0x2600 <= ord(ch) <= 0x27BF or 0x2B00 <= ord(ch) <= 0x2BFF or ord(ch) in (0xFE0F, 0x200D)
    t = ''.join('\0' if emoji(ch) else ch for ch in t)
    t = re.sub(r'\s*\0[\0\s]*', lambda m: ' ' if m.start() == 0 or t[m.start() - 1] in '?!.:,' else ': ', t)
    t = re.sub(r'\s+', ' ', t).strip()
    return t.rstrip(':').strip()


def find(yt, ep_id, lang, name):
    for p in (os.path.join(yt, LANGS[lang], ep_id, name), os.path.join(yt, 'out', ep_id, name)):
        if os.path.exists(p):
            return p
    return None


def main():
    yt = sys.argv[1]
    site = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
    spec = json.load(open(os.path.join(site, 'content', 'videos', 'episodes.json'), encoding='utf-8'))
    only = sys.argv[2:]  # optional: just these episodes, e.g. ep09 ep10
    for ep_id, E in spec.items():
        if only and ep_id not in only:
            continue
        lines_path = os.path.join(yt, 'studio', ep_id, 'lines.json')
        if not os.path.exists(lines_path):
            print(f'{ep_id}: not made yet (no {lines_path}); its post stays as it is')
            continue
        lines = json.load(open(lines_path, encoding='utf-8'))['lines']
        starts = {i: h for i, h in E['chapters']}
        out = {'id': ep_id, 'slug': E['slug'], 'date': E['date'], 'langs': {}}
        for lang in LANGS:
            info_path = find(yt, ep_id, lang, f'UPLOAD-{ep_id}-{lang}.md')
            if not info_path:
                continue
            info = open(info_path, encoding='utf-8').read()
            title = clean_title(re.search(r'^## Title\s*\n(.+)', info, re.M).group(1))
            desc = re.search(r'^## Description\s*\n(.+)', info, re.M).group(1).strip()
            sections = [['', []]]
            for i, line in enumerate(lines):
                if i in starts:
                    sections.append([starts[i][lang], []])
                text = line['text'].get(lang)
                if text and text not in SKIP:
                    sections[-1][1].append(text)
            sections = [s for s in sections if s[1]]
            out['langs'][lang] = {'title': title, 'series': E['series'][lang], 'video_title': E['video_title'][lang], 'desc': desc, 'sections': sections}
            thumb = find(yt, ep_id, lang, f'rasivani-{ep_id}-{lang}-thumbnail.jpg')
            if thumb:
                os.makedirs(os.path.join(site, 'images', 'videos'), exist_ok=True)
                shutil.copyfile(thumb, os.path.join(site, 'images', 'videos', f'{ep_id}-{lang}.jpg'))
        dest = os.path.join(site, 'content', 'videos', ep_id + '.mjs')
        with open(dest, 'w', encoding='utf-8') as f:
            f.write('// Generated by tools/episode-post.py from the YouTube script. Edit freely.\nexport default ')
            json.dump(out, f, ensure_ascii=False, indent=1)
            f.write(';\n')
        print(f'{ep_id}: {", ".join(f"{l} ({len(v["sections"])} sections)" for l, v in out["langs"].items())}')


if __name__ == '__main__':
    main()
