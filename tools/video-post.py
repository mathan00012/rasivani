#!/usr/bin/env python3
"""Turn a YouTube episode script into a blog post for rasivani.com.

    python3 tools/video-post.py EPISODE.py UPLOAD-INFO.md SLUG DATE [--groups "open|ring|moon,cards|end"]

EPISODE.py   the video-maker script (TITLE, SERIES, LINES with ta/te/en text)
UPLOAD-INFO  the upload notes (YouTube title, description and chapter list per language)
SLUG         web address of the post, e.g. 27-nakshatras-month-names
DATE         YYYY-MM-DD; the post goes live on this day
--groups     which scenes form each chapter, in order (| between chapters, comma inside one).
             Without it, every run of the same scene becomes its own section.

Writes content/videos/<epNN>.mjs. Copy the thumbnails to images/videos/<epNN>-<lang>.jpg,
and paste the YouTube links into content/videos/youtube.txt once the videos are uploaded.
"""
import json, re, runpy, sys, os

def main():
    args = sys.argv[1:]
    groups = None
    if '--groups' in args:
        i = args.index('--groups'); groups = [g.split(',') for g in args[i + 1].split('|')]; del args[i:i + 2]
    ep_path, info_path, slug, date = args
    ep = runpy.run_path(ep_path)
    ep_id = re.search(r'episode(\d+)', os.path.basename(ep_path)).group(1)
    ep_id = 'ep' + ep_id.zfill(2)
    info = open(info_path, encoding='utf-8').read()
    # Upload notes: sections "## Tamil ...", "## Telugu ...", "## English ..."
    names = {'ta': 'Tamil', 'te': 'Telugu', 'en': 'English'}
    runs = []  # [(scene, [line dicts])]
    for scene, text in ep['LINES']:
        if not text: continue
        if runs and runs[-1][0] == scene: runs[-1][1].append(text)
        else: runs.append((scene, [text]))
    if groups:
        order = [s for g in groups for s in g]
        assert [r[0] for r in runs] == order, f'scenes {[r[0] for r in runs]} do not match --groups {order}'
        chunks, k = [], 0
        for g in groups:
            chunks.append([t for r in runs[k:k + len(g)] for t in r[1]]); k += len(g)
    else:
        chunks = [r[1] for r in runs]
    out = {'id': ep_id, 'slug': slug, 'date': date, 'langs': {}}
    for lang, name in names.items():
        m = re.search(r'^## ' + name + r'.*?$(.*?)(?=^## |\Z)', info, re.S | re.M)
        if not m or lang not in ep['TITLE']: continue
        block = m.group(1)
        title = re.search(r'\*\*Title:\*\*\s*(.+)', block).group(1).strip()
        title = re.sub(r'\s*\|\s*RasiVani\s*$', '', title)
        desc_lines = block.split('**Description:**', 1)[1].strip().splitlines()
        desc = desc_lines[0].strip()
        chapters = [re.sub(r'^\d+:\d+\s+', '', l.strip()) for l in desc_lines if re.match(r'^\d+:\d+\s', l.strip())]
        sections = []
        for i, chunk in enumerate(chunks):
            head = chapters[i] if groups and i < len(chapters) else ''
            sections.append([head, [t[lang] for t in chunk if t.get(lang)]])
        out['langs'][lang] = {'title': title, 'series': ep['SERIES'][lang], 'video_title': ep['TITLE'][lang], 'desc': desc, 'sections': sections}
    dest = os.path.join(os.path.dirname(__file__), '..', 'content', 'videos', ep_id + '.mjs')
    with open(dest, 'w', encoding='utf-8') as f:
        f.write('// Generated by tools/video-post.py from the YouTube script. Edit freely.\nexport default ')
        f.write(json.dumps(out, ensure_ascii=False, indent=1))
        f.write(';\n')
    print('wrote', os.path.normpath(dest))

main()
